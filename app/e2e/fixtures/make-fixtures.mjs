// Generates small single-page PDF pairs with known differences (our own test fixtures, no dependencies).
// Usage: node e2e/fixtures/make-fixtures.mjs   (writes *_a.pdf / *_b.pdf next to this script)
// Coordinates below are PDF user space (origin bottom-left, US Letter 612 x 792 pt).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

/** Minimal PDF 1.4 writer: one page, Helvetica, the given content stream. */
function pdf(content) {
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    `<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}\nendstream`,
  ];
  let out = '%PDF-1.4\n%\xe2\xe3\xcf\xd3\n';
  const offs = [];
  objs.forEach((o, i) => { offs.push(Buffer.byteLength(out, 'latin1')); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = Buffer.byteLength(out, 'latin1');
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offs.map(o => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

const text = (s, x, y, size = 36) => `BT /F1 ${size} Tf ${x} ${y} Td (${s}) Tj ET`;
/** Filled box drawn with the `re` operator. */
const boxRe = (x, y, w, h, rgb = '0 0 0') => `q ${rgb} rg ${x} ${y} ${w} ${h} re f Q`;
/** The same box drawn as a plain path (m / l / h) - some editors write rectangles this way. */
const boxPath = (x, y, w, h, rgb = '0 0 0') => `q ${rgb} rg ${x} ${y} m ${x + w} ${y} l ${x + w} ${y + h} l ${x} ${y + h} l h f Q`;
/** Same box placed with a transformation matrix (Inkscape style: cm + unit-ish coordinates). */
const boxCm = (x, y, w, h) => `q 1 0 0 1 ${x} ${y} cm 0 0 0 rg 0 0 ${w} ${h} re f Q`;
const frame = 'q 0.5 w 0 0 0 RG 36 36 540 720 re S Q'; // unchanged page border
const caption = (s) => text(s, 48, 60, 10);

/** name -> [content A, content B, what changed] */
const cases = {
  // the user's case: "Hello" moved, black box resized (anchored at its lower-left corner)
  hello_box: [
    [frame, text('Hello', 100, 650), boxRe(100, 400, 100, 60)],
    [frame, text('Hello', 220, 610), boxRe(100, 400, 160, 90)],
    'Text "Hello" moved by (+120, -40) pt; box 100x60 -> 160x90 pt, lower-left corner fixed',
  ],
  // same without the page border: just "Hello" and the box, like the user's rev1/rev3 test files
  hello_box_bare: [
    [text('Hello', 100, 650), boxRe(100, 400, 100, 60)],
    [text('Hello', 220, 610), boxRe(100, 400, 160, 90)],
    'As hello_box, without the page border',
  ],
  text_move_50: [[frame, text('Hello', 100, 650)], [frame, text('Hello', 150, 650)], 'Text "Hello" moved right 50 pt'],
  text_move_150: [[frame, text('Hello', 100, 650)], [frame, text('Hello', 250, 550)], 'Text "Hello" moved (+150, -100) pt'],
  box_resize_corner: [[frame, boxRe(100, 400, 100, 60)], [frame, boxRe(100, 400, 160, 90)], 'Box 100x60 -> 160x90 pt, corner anchored (re fill)'],
  box_resize_center: [[frame, boxRe(250, 400, 100, 60)], [frame, boxRe(220, 385, 160, 90)], 'Box 100x60 -> 160x90 pt, centre fixed (re fill)'],
  box_resize_path: [[frame, boxPath(100, 400, 100, 60)], [frame, boxPath(100, 400, 160, 90)], 'Box 100x60 -> 160x90 pt drawn as m/l/h path'],
  box_resize_cm: [[frame, boxCm(100, 400, 100, 60)], [frame, boxCm(100, 400, 160, 90)], 'Box 100x60 -> 160x90 pt placed with cm'],
  box_move: [[frame, boxRe(100, 400, 100, 60)], [frame, boxRe(300, 300, 100, 60)], 'Box 100x60 moved (+200, -100) pt'],
  box_color: [[frame, boxRe(100, 400, 100, 60)], [frame, boxRe(100, 400, 100, 60, '0.9 0.1 0.1')], 'Box fill black -> red'],
  combo: [
    [frame, caption('Combination test'), text('Hello', 100, 650), text('World', 100, 300, 24), boxRe(350, 600, 100, 60), boxPath(350, 200, 80, 40)],
    [frame, caption('Combination test'), text('Hello', 160, 700), text('World', 100, 300, 24), boxRe(320, 585, 160, 90), boxPath(350, 120, 80, 40), boxRe(100, 450, 50, 50)],
    'Hello moved (+60, +50); World unchanged; re box resized about its centre; path box moved down 80; new 50x50 box added',
  ],
};

const readme = ['# Synthetic fixtures', '', 'Generated by `make-fixtures.mjs` (run `node e2e/fixtures/make-fixtures.mjs` from `app/`). Each case is a pair `<case>_a.pdf` (old) / `<case>_b.pdf` (new):', ''];
for (const [name, [a, b, what]] of Object.entries(cases)) {
  writeFileSync(join(here, `${name}_a.pdf`), pdf(a.join('\n')));
  writeFileSync(join(here, `${name}_b.pdf`), pdf(b.join('\n')));
  readme.push(`- \`${name}\`: ${what}`);
}
writeFileSync(join(here, 'README.md'), readme.join('\n') + '\n');
console.log(`wrote ${Object.keys(cases).length} pairs to ${here}`);
